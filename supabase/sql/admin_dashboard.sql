-- Puts a past filter version back on the map (no new version) and resets the
-- draft to it.
create or replace function public.make_filters_version_live(p_version_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_config jsonb;
  v_version_no integer;
begin
  if not public.is_admin() then
    raise exception 'Only admins can change the live map filters' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(hashtext('publish_filters'));

  select config, version_no into v_config, v_version_no
  from public.filters_versions where id = p_version_id
  for update;
  if v_config is null then
    raise exception 'Filter version % not found', p_version_id using errcode = 'P0002';
  end if;

  update public.filters_versions set is_current = false where is_current and id <> p_version_id;
  update public.filters_versions set is_current = true where id = p_version_id;

  insert into public.filters_draft (id, config, updated_at, updated_by)
  values (true, v_config, now(), lower(coalesce(auth.jwt() ->> 'email', '')))
  on conflict (id) do update
    set config = excluded.config, updated_at = excluded.updated_at, updated_by = excluded.updated_by;

  return jsonb_build_object('version_id', p_version_id, 'version_no', v_version_no, 'config', v_config);
end;
$$;

