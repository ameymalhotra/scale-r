-- Discards the saved filter draft: back to the live version, or to the map's
-- built-in filters when nothing has been published yet (no draft row).
create or replace function public.reset_filters_draft()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_config jsonb;
begin
  if not public.is_admin() then
    raise exception 'Only admins can reset the filter draft' using errcode = '42501';
  end if;

  select config into v_config from public.filters_versions where is_current;
  if v_config is null then
    delete from public.filters_draft where id;
  else
    insert into public.filters_draft (id, config, updated_at, updated_by)
    values (true, v_config, now(), lower(coalesce(auth.jwt() ->> 'email', '')))
    on conflict (id) do update
      set config = excluded.config, updated_at = excluded.updated_at, updated_by = excluded.updated_by;
  end if;

  return jsonb_build_object('ok', true);
end;
$$;

revoke all on function public.reset_filters_draft() from public, anon;
grant execute on function public.reset_filters_draft() to authenticated;

