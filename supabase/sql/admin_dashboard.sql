-- ── save_draft_changes ──────────────────────────────────────────────────────
-- Applies one "Save draft" from /admin atomically. Runs as the caller, so the
-- projects_draft RLS policy (admins only) still applies.
--   p_updates  jsonb array of full rows with existing ids
--   p_inserts  jsonb array of new rows (ids assigned here)
--   p_deletes  ids to remove

create or replace function public.save_draft_changes(
  p_updates jsonb default '[]'::jsonb,
  p_inserts jsonb default '[]'::jsonb,
  p_deletes bigint[] default '{}'
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_deleted integer;
  v_updated integer;
  v_inserted integer;
begin
  if not public.is_admin() then
    raise exception 'Only admins can edit the draft' using errcode = '42501';
  end if;

  delete from public.projects_draft where id = any(coalesce(p_deletes, '{}'));
  get diagnostics v_deleted = row_count;

  update public.projects_draft d set
    implementa = r.implementa,
    project_na = r.project_na,
    city = r.city,
    latitude = r.latitude,
    longitude = r.longitude,
    link_to_da = r.link_to_da,
    infrastruc = r.infrastruc,
    disaster_f = r.disaster_f,
    new_15_25_ = r.new_15_25_,
    project_status = r.project_status,
    status_category = r.status_category,
    estimated_cost = r.estimated_cost,
    project_st = r.project_st,
    additional = r.additional,
    tract_geoid = r.tract_geoid
  from jsonb_populate_recordset(null::public.projects_draft, coalesce(p_updates, '[]'::jsonb)) r
  where d.id = r.id;
  get diagnostics v_updated = row_count;

  insert into public.projects_draft (
    implementa, project_na, city, latitude, longitude, link_to_da, infrastruc,
    disaster_f, new_15_25_, project_status, status_category, estimated_cost,
    project_st, additional, tract_geoid
  )
  select
    r.implementa, r.project_na, r.city, r.latitude, r.longitude, r.link_to_da, r.infrastruc,
    r.disaster_f, r.new_15_25_, r.project_status, r.status_category, r.estimated_cost,
    r.project_st, r.additional, r.tract_geoid
  from jsonb_populate_recordset(null::public.projects_draft, coalesce(p_inserts, '[]'::jsonb)) r;
  get diagnostics v_inserted = row_count;

  return jsonb_build_object('deleted', v_deleted, 'updated', v_updated, 'inserted', v_inserted);
end;
$$;

revoke all on function public.save_draft_changes(jsonb, jsonb, bigint[]) from public, anon;
