  end if;
  if length(v_name) > 120 then
    raise exception 'Version names can be at most 120 characters' using errcode = '22023';
  end if;

  perform pg_advisory_xact_lock(hashtext('publish_filters'));

  select config into v_config from public.filters_draft where id;
  if v_config is null then
    raise exception 'Save the filter draft before publishing' using errcode = '22023';
  end if;

  v_version_no := nextval('public.filters_version_no_seq');
  update public.filters_versions set is_current = false where is_current;
  insert into public.filters_versions (version_no, name, note, config, is_current, created_by)
  values (v_version_no, v_name, btrim(p_note), v_config, true, lower(coalesce(auth.jwt() ->> 'email', '')))
  returning id into v_version_id;

  return jsonb_build_object('version_id', v_version_id, 'version_no', v_version_no, 'config', v_config);
end;
$$;

