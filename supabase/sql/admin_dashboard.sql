-- `name` duplicates `city` and `categories` duplicates `additional` in the
-- seeded data. /admin only edits `city` and `additional`, so keep the
-- duplicates in step unless they had already diverged.
create or replace function public.projects_draft_touch()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    new.name := coalesce(new.name, new.city);
    new.categories := coalesce(new.categories, new.additional);
  else
    if new.city is distinct from old.city and old.name is not distinct from old.city then
      new.name := new.city;
    end if;
    if new.additional is distinct from old.additional and old.categories is not distinct from old.additional then
      new.categories := new.additional;
    end if;
  end if;
  new.updated_at := now();
  new.updated_by := coalesce(auth.jwt() ->> 'email', new.updated_by);
  return new;
end;
$$;

drop trigger if exists projects_draft_touch on public.projects_draft;
