-- ── publish_draft ───────────────────────────────────────────────────────────

create or replace function public.publish_draft(p_note text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_version_no integer;
  v_version_id bigint;
  v_row_count integer;
begin
  if not public.is_admin() then
    raise exception 'Only admins can publish' using errcode = '42501';
  end if;
  if p_note is null or btrim(p_note) = '' then
    raise exception 'A publish note is required' using errcode = '22023';
  end if;

  -- Serialize concurrent publishes.
  perform pg_advisory_xact_lock(hashtext('publish_draft'));

  v_version_no := nextval('public.projects_version_no_seq');

  update public.projects_versions set is_current = false where is_current;

  insert into public.projects_versions (version_no, created_by, note, row_count, snapshot, is_current)
  select
    v_version_no,
    v_email,
    btrim(p_note),
    count(*),
    coalesce(jsonb_agg(to_jsonb(d) - 'updated_at' - 'updated_by' order by d.id), '[]'::jsonb),
    true
  from public.projects_draft d
  returning id, row_count into v_version_id, v_row_count;

  -- Supabase's safeupdate extension rejects DELETE without a WHERE clause.
  delete from public.projects_merged_conf1 where true;

  insert into public.projects_merged_conf1 (
    id, project_na, name, city, latitude, longitude, infrastruc, categories,
    disaster_f, new_15_25_, project_st, project_en, project_status, status_category,
    estimated_cost, implementa, link_to_da, additional, tract_geoid
  )
  select
    id, project_na, name, city, latitude, longitude, infrastruc, categories,
    disaster_f, new_15_25_, project_st, project_en, project_status, status_category,
    estimated_cost, implementa, link_to_da, additional, tract_geoid
  from public.projects_draft;

  return jsonb_build_object(
    'version_id', v_version_id,
    'version_no', v_version_no,
    'row_count', v_row_count
  );
end;
$$;

revoke all on function public.publish_draft(text) from public, anon;
grant execute on function public.publish_draft(text) to authenticated;

-- ── make_version_live ───────────────────────────────────────────────────────
-- Puts a past version back on the map without creating a new version: replaces
-- projects_merged_conf1 and the draft with its snapshot and marks it current.
-- Called by the publish-projects edge function, which then rebuilds the GeoJSON.

create or replace function public.make_version_live(p_version_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_snapshot jsonb;
  v_version_no integer;
  v_row_count integer;
begin
  if not public.is_admin() then
    raise exception 'Only admins can change the live version' using errcode = '42501';
  end if;

  perform pg_advisory_xact_lock(hashtext('publish_draft'));

  select snapshot, version_no into v_snapshot, v_version_no
  from public.projects_versions where id = p_version_id
  for update;
  if v_snapshot is null then
    raise exception 'Version % not found', p_version_id using errcode = 'P0002';
  end if;

  update public.projects_versions set is_current = false where is_current and id <> p_version_id;
  update public.projects_versions set is_current = true where id = p_version_id;

  delete from public.projects_merged_conf1 where true;

  insert into public.projects_merged_conf1 (
    id, project_na, name, city, latitude, longitude, infrastruc, categories,
    disaster_f, new_15_25_, project_st, project_en, project_status, status_category,
    estimated_cost, implementa, link_to_da, additional, tract_geoid
  )
  select
    r.id, r.project_na, r.name, r.city, r.latitude, r.longitude, r.infrastruc, r.categories,
    r.disaster_f, r.new_15_25_, r.project_st, r.project_en, r.project_status, r.status_category,
    r.estimated_cost, r.implementa, r.link_to_da, r.additional, r.tract_geoid
  from jsonb_populate_recordset(null::public.projects_draft, v_snapshot) r;

  get diagnostics v_row_count = row_count;

  delete from public.projects_draft where true;

  insert into public.projects_draft (
    id, project_na, name, city, latitude, longitude, infrastruc, categories,
    disaster_f, new_15_25_, project_st, project_en, project_status, status_category,
    estimated_cost, implementa, link_to_da, additional, tract_geoid
  )
  select
    id, project_na, name, city, latitude, longitude, infrastruc, categories,
    disaster_f, new_15_25_, project_st, project_en, project_status, status_category,
    estimated_cost, implementa, link_to_da, additional, tract_geoid
  from public.projects_merged_conf1;

  perform setval(
    'public.projects_row_id_seq',
    greatest(
      (select last_value from public.projects_row_id_seq),
      coalesce((select max(id) from public.projects_merged_conf1), 0),
      1
    )
  );

  return jsonb_build_object(
    'version_id', p_version_id,
    'version_no', v_version_no,
    'row_count', v_row_count
  );
end;
$$;

